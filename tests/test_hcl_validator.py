"""Unit tests for the HCL syntax validator."""

from pathlib import Path

from click.testing import CliRunner

from calm_forge.cli import cli
from calm_forge.hcl_validator import validate_hcl_syntax

EXAMPLES_DIR = Path(__file__).parent.parent / "examples"


# ---------------------------------------------------------------------------
# Valid HCL cases
# ---------------------------------------------------------------------------


def test_valid_empty_block():
    hcl = 'component "web" "frontend" {\n}\n'
    assert validate_hcl_syntax(hcl) == []


def test_valid_nested_blocks():
    hcl = """
required_providers {
  kubernetes = {
    source  = "hashicorp/kubernetes"
    version = "~> 2.30"
  }
}
"""
    assert validate_hcl_syntax(hcl) == []


def test_valid_attributes():
    hcl = 'address = "https://vault.example.com"\ntoken   = var.vault_token\n'
    assert validate_hcl_syntax(hcl) == []


def test_valid_multiline_nested():
    hcl = """
provider "vault" "this" {
  address = var.vault_addr
  token   = var.vault_token
}

component "app" "api" {
  source  = "./modules/k8s-deployment"
  version = "~> 1.0"

  inputs = {
    namespace = var.namespace
    image     = var.api_image
  }
}
"""
    assert validate_hcl_syntax(hcl) == []


# ---------------------------------------------------------------------------
# Unbalanced brace cases
# ---------------------------------------------------------------------------


def test_unbalanced_open_brace():
    hcl = 'component "web" {\n  inputs = {\n'
    errors = validate_hcl_syntax(hcl)
    assert len(errors) == 1
    assert "never closed" in errors[0]


def test_unbalanced_close_brace():
    hcl = 'component "web" {\n}\n}\n'
    errors = validate_hcl_syntax(hcl)
    assert len(errors) == 1
    assert "unexpected" in errors[0].lower() or "closing" in errors[0].lower()


# ---------------------------------------------------------------------------
# Unterminated string
# ---------------------------------------------------------------------------


def test_unterminated_string_newline():
    hcl = 'address = "https://vault.example.com\ntoken = var.vault_token\n'
    errors = validate_hcl_syntax(hcl)
    assert any("unterminated string" in e for e in errors)


def test_unterminated_string_eof():
    hcl = 'address = "https://vault.example.com'
    errors = validate_hcl_syntax(hcl)
    assert any("unterminated string" in e for e in errors)


# ---------------------------------------------------------------------------
# Braces inside strings are ignored
# ---------------------------------------------------------------------------


def test_brace_inside_string_ignored():
    hcl = 'label = "hello { world }"\n'
    assert validate_hcl_syntax(hcl) == []


def test_brace_inside_string_does_not_affect_depth():
    hcl = 'component "x" {\n  label = "{ not a block }"\n}\n'
    assert validate_hcl_syntax(hcl) == []


# ---------------------------------------------------------------------------
# Braces inside comments are ignored
# ---------------------------------------------------------------------------


def test_brace_inside_line_comment_hash():
    hcl = "# this is { a comment }\ncomponent \"x\" {\n}\n"
    assert validate_hcl_syntax(hcl) == []


def test_brace_inside_line_comment_slash():
    hcl = '// this is { a comment }\ncomponent "x" {\n}\n'
    assert validate_hcl_syntax(hcl) == []


def test_brace_inside_block_comment():
    hcl = '/* open { and close } */\ncomponent "x" {\n}\n'
    assert validate_hcl_syntax(hcl) == []


def test_unterminated_block_comment():
    hcl = '/* this comment never ends\ncomponent "x" {\n}\n'
    errors = validate_hcl_syntax(hcl)
    assert any("block comment" in e for e in errors)


