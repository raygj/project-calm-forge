# ---------------------------------------------------------------------------
# Integration tests: --validate flag on the CLI
# ---------------------------------------------------------------------------


def test_cli_generate_validate_flag_passes(tmp_path):
    """generate --validate on fsi-3tier exits 0 and prints success message."""
    ex = EXAMPLES_DIR / "fsi-3tier"
    result = CliRunner().invoke(cli, [
        "generate",
        "--calm", str(ex / "instantiation.json"),
        "--decorator", str(ex / "decorator.json"),
        "--catalog", str(ex / "catalog.json"),
        "--output-dir", str(tmp_path),
        "--validate",
    ])
    assert result.exit_code == 0, result.output
    assert "validation passed" in result.output


def test_cli_validate_flag_reports_file_count(tmp_path):
    """generate --validate reports correct number of HCL files validated."""
    ex = EXAMPLES_DIR / "fsi-3tier"
    result = CliRunner().invoke(cli, [
        "generate",
        "--calm", str(ex / "instantiation.json"),
        "--decorator", str(ex / "decorator.json"),
        "--catalog", str(ex / "catalog.json"),
        "--output-dir", str(tmp_path),
        "--validate",
    ])
    assert result.exit_code == 0, result.output
    # Default generate produces 3 HCL files
    assert "3 files OK" in result.output


def test_cli_validate_flag_all_examples_pass(tmp_path):
    """generate --validate exits 0 for all FSI examples."""
    all_examples = [
        "fsi-3tier",
        "fsi-event-driven",
        "fsi-microservices-mesh",
        "fsi-mongodb-multiregion",
    ]
    for example in all_examples:
        ex = EXAMPLES_DIR / example
        out = tmp_path / example
        result = CliRunner().invoke(cli, [
            "generate",
            "--calm", str(ex / "instantiation.json"),
            "--decorator", str(ex / "decorator.json"),
            "--catalog", str(ex / "catalog.json"),
            "--output-dir", str(out),
            "--validate",
        ])
        assert result.exit_code == 0, f"{example}: {result.output}"
        assert "validation passed" in result.output, f"{example}: missing success message"
